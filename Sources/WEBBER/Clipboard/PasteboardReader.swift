import AppKit

enum PasteboardReadResult {
    case item(ClipboardItem)
    /// Marked concealed/transient by the source app (password managers do this). Never stored.
    case concealed
    case empty
}

/// Reads the richest useful representation from a pasteboard, once, on an explicit catch.
/// Priority: Finder files → images → URLs → text (code is text that looks like code).
enum PasteboardReader {
    static let concealedTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"), .init("com.agilebits.onepassword")
    ]
    static let imageTypes: [NSPasteboard.PasteboardType] = [.png, .tiff, .init("public.jpeg"), .init("public.heic")]
    /// Only these representations are retained for Copy Again; nothing else is copied out of the pasteboard.
    static let retainedTypes: [NSPasteboard.PasteboardType] = [.string, .rtf, .html, .URL, .init("public.url-name"), .png, .tiff]
    static let maxImageBytes = 40_000_000

    static func read(_ board: NSPasteboard = .general, id: Int) -> PasteboardReadResult {
        guard let types = board.types, !types.isEmpty else { return .empty }
        if types.contains(where: concealedTypes.contains) { return .concealed }
        let item = board.pasteboardItems?.first

        // Files: Finder puts file URLs (one per item). A copied image *file* stays a file.
        let files = (board.readObjects(forClasses:[NSURL.self],options:[.urlReadingFileURLsOnly:true]) as? [URL]) ?? []
        if !files.isEmpty {
            return .item(ClipboardItem(id:id,kind:.file,representations:[],text:nil,url:nil,fileURLs:files,image:nil))
        }

        // Images: screenshots, browser "Copy Image", Preview. Keep the original bytes for Copy Again.
        if let type = item?.availableType(from:imageTypes), let data = item?.data(forType:type), data.count <= maxImageBytes, let image = NSImage(data:data) {
            var reps = retained(item)
            if !reps.contains(where: { $0.0 == .png || $0.0 == .tiff }) {
                reps.append((.png, ItemPreview.png(image) ?? data))
            }
            return .item(ClipboardItem(id:id,kind:.image,representations:reps,text:nil,url:nil,fileURLs:[],image:image))
        }

        let string = board.string(forType:.string)
        // URLs: an explicit public.url, or a string that is exactly one web address.
        let explicit = board.string(forType:.URL).flatMap(webURL)
        if let url = explicit ?? string.flatMap(webURL) {
            var reps = retained(item)
            if !reps.contains(where: { $0.0 == .string }) { reps.append((.string, Data(url.absoluteString.utf8))) }
            return .item(ClipboardItem(id:id,kind:.url,representations:reps,text:string,url:url,fileURLs:[],image:nil))
        }

        if let string, !string.trimmingCharacters(in:.whitespacesAndNewlines).isEmpty {
            return .item(ClipboardItem(id:id,kind:looksLikeCode(string) ? .code : .text,representations:retained(item),text:string,url:nil,fileURLs:[],image:nil))
        }
        return .empty
    }

    private static func retained(_ item: NSPasteboardItem?) -> [(NSPasteboard.PasteboardType, Data)] {
        guard let item else { return [] }
        return retainedTypes.compactMap { type in
            guard item.types.contains(type), let data = item.data(forType:type) else { return nil }
            return (type, data)
        }
    }

    static func webURL(_ string: String) -> URL? {
        let trimmed = string.trimmingCharacters(in:.whitespacesAndNewlines)
        guard !trimmed.contains(where: \.isWhitespace), trimmed.count < 4000,
              let url = URL(string:trimmed), let scheme = url.scheme?.lowercased(),
              ["http","https"].contains(scheme), url.host?.contains(".") == true else { return nil }
        return url
    }

    /// Cheap heuristic: brackets, statement punctuation, indentation, or common keywords.
    static func looksLikeCode(_ s: String) -> Bool {
        let lines = s.split(separator:"\n",omittingEmptySubsequences:false)
        var score = 0
        if s.contains("{") && s.contains("}") { score += 2 }
        if s.contains(";") { score += 1 }
        if s.contains("=>") || s.contains("->") || s.contains(":=") || s.contains("==") { score += 1 }
        if lines.contains(where: { $0.hasPrefix("    ") || $0.hasPrefix("\t") }) { score += 1 }
        let keywords = ["func ","def ","let ","var ","const ","return ","import ","class ","struct ","if (","for (","#include","fn ","package ","SELECT ","=> {","console.","print(","</"]
        score += keywords.filter { s.contains($0) }.count*2
        return score >= 3
    }
}
